def rec(sid, fam, vis, role, meaning=None, aliases=None):
    return {"symbol_id": sid, "script_family": fam, "visible_symbol": vis, "symbolic_role": role,
            "meaning_invariant": list(meaning or ["m-" + sid.lower()]), "aliases": list(aliases or [])}


