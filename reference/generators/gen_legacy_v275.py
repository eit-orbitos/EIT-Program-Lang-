def state(recs):
    art = {"frozen_artifact_id": "FROZEN-LEG", "frozen_registry_snapshot": {"registry_records": recs}}
    st = {"restored_state_id": "RS-LEG", "release_id": "REL-LEG", "frozen_artifact_id": "FROZEN-LEG",
          "frozen_artifact_sha256": artifact_sha256(art), "current_version_id": "V-LEG", "frozen_artifact": art}
    st["restored_state_sha256"] = sha256_json({k: v for k, v in st.items() if k != "restored_state_sha256"})
    return st


def emit(name, recs, query=None, tr=None, check=None, call=""):
    st = state(recs)
    q = Q(st, query) if query is not None else None
    t = T(st, tr[0], tr[1]) if tr is not None else None
    r = B(st, query_result=q, translation_result=t)
    if check is not None and not check(r):
        print("FIXTURE CHECK FAILED:", name)
        sys.exit(2)
    doc = {"artifact": st["frozen_artifact"], "receipt": r,
           "provenance": {"commit": COMMIT, "package_version": getattr(eit_program_lang, "__version__", None),
                          "python": sys.version, "call": call}}
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as fh:
        json.dump(doc, fh, ensure_ascii=False, indent=1)
    print("wrote", name)


